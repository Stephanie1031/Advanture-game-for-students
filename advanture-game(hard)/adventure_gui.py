    # ------------------------------------------------------------ 游戏操作
    def perform(self, command, method_name, *args):
        """执行一次操作：打印命令 -> 调用学生代码 -> 显示输出 -> 给出提示 -> 刷新。"""
        self.log('\nadventure> ' + command, 'input')
        before = self.session.signature()
        output, error = self.session.call(method_name, *args)
        if output:
            self.log(output)
        if error:
            self.log(error, 'error')
            self.log(self.session.error_hint(method_name), 'hint')
        elif method_name == 'talk_to' and not output.strip():
            # 对话一定会打印台词，这里什么都没打印，说明方法还没写完。
            self.log(self.session.no_change_hint('talk_to'), 'hint')
        elif method_name in ('go_to', 'take', 'unlock') and before == self.session.signature():
            self.log(self.session.no_change_hint(method_name), 'hint')
        self.refresh()
        self.check_win()

    def do_look(self):
        self.perform('look', 'look')

    def do_backpack(self):
        self.perform('check backpack', 'check_backpack')

    def do_go(self, name):
        self.perform('go to {}'.format(name), 'go_to', name)

    def do_take(self, name):
        self.perform('take {}'.format(name), 'take', name)

    def do_talk(self, name):
        self.perform('talk to {}'.format(name), 'talk_to', name)

    def do_unlock(self, name):
        self.perform('unlock {}'.format(name), 'unlock', name)

    def run_command(self, event=None):
        line = self.entry.get().strip()
        if not line:
            return 'break'
        self.entry.delete(0, 'end')
        try:
            operator, operand = self.session.parse(line)
        except SyntaxError as error:
            self.log('\nadventure> ' + line, 'input')
            self.log('ERROR: {}'.format(error), 'error')
            self.log(T('命令格式不对。点“命令列表 Help”看看正确写法，例如 `go to 大草坪`、'
                       '`talk to 杰瑞`、`take Lemon`。',
                       'That command is malformed. Click "Help" for the correct form, e.g. '
                       '`go to 大草坪`, `talk to 杰瑞`, `take Lemon`.'), 'hint')
            return 'break'
        except Exception:
            self.log('\nadventure> ' + line, 'input')
            self.log(traceback.format_exc(), 'error')
            return 'break'
        self._dispatch(operator, operand, line)
        return 'break'

    def _dispatch(self, operator, operand, line=''):
        if operator == 'help':
            self.show_help()
        elif operator == 'look':
            self.perform('look', 'look')
        elif operator == 'check_backpack':
            self.perform('check backpack', 'check_backpack')
        elif operator == 'go_to':
            self.perform('go to {}'.format(operand), 'go_to', operand)
        elif operator == 'take':
            self.perform('take {}'.format(operand), 'take', operand)
        elif operator == 'talk_to':
            self.perform('talk to {}'.format(operand), 'talk_to', operand)
        elif operator == 'unlock':
            self.perform('unlock {}'.format(operand), 'unlock', operand)
        else:
            self.log('\nadventure> ' + line, 'input')
            self.log(T('无效命令：{}。点“命令列表 Help”看看有哪些命令。'.format(operator),
                       'Invalid command: {}. Click "Help" to see the command list.'.format(operator)),
                     'error')

    def check_win(self):
        if self.win_shown or not self.session.is_win():
            return
        self.win_shown = True
        message = getattr(self.session.adventure, 'WIN_MESSAGE', None) or T(
            '你在大礼堂赶上了学习聚会，恭喜通关！',
            'You arrived at the Auditorium in time. Congratulations!')
        self.log(message, 'win')
        messagebox.showinfo(T('恭喜通关', 'You win'), message)

    # ------------------------------------------------------------ 其它按钮
    def show_help(self):
        self.log(T('\n可用命令 / available commands:', '\nAvailable commands:'), 'hint')
        for usage in self.session.command_formats():
            self.log('    ' + usage, 'hint')
        self.log(T('提示：命令里的地名既可以用中文，也可以用英文别名，例如 go to GBC。',
                   'Tip: place names accept both Chinese and English aliases, e.g. `go to GBC`.'), 'hint')

