    # ------------------------------------------------------------ 界面搭建
    def _configure_style(self):
        style = ttk.Style(self.root)
        family = self.font_family
        if not family:
            return
        for name, size in (('TLabel', 12), ('TButton', 12), ('TLabelframe.Label', 12),
                           ('TCheckbutton', 12), ('TCombobox', 12), ('TEntry', 12)):
            style.configure(name, font=(family, size))
        style.configure('Title.TLabel', font=(family, 17, 'bold'))
        style.configure('Place.TLabel', font=(family, 15, 'bold'))
        style.configure('Goal.TLabel', font=(family, 12), foreground='#555555')
        style.configure('Desc.TLabel', font=(family, 11), foreground='#666666')

    def _build_widgets(self):
        self.root.title(WINDOW_TITLE)
        self.root.columnconfigure(0, weight=1)
        # 主体部分按内容取自然高度（不会被压扁），多余的/不足的高度都给日志区
