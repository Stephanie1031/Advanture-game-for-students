def T(zh, en):
    """按照当前界面语言返回文本 / Return text in the currently selected language."""
    if LANG == 'zh':
        return zh
    if LANG == 'en':
        return en
    if '\n' in zh or '\n' in en:
        return zh + '\n' + en
    return zh + ' / ' + en


def _read_lines(path):
    """读取源文件的所有行（容错编码）/ Read a source file, tolerating bad encodings."""
    try:
        with open(path, 'r', encoding='utf-8', errors='replace') as handle:
            return handle.read().splitlines()
    except OSError:
        return []


def _localize(name, data_module):
    """把英文别名换成 data.py 中的标准名字（与 adventure.py 的规则保持一致）。"""
    aliases = getattr(data_module, 'ALIASES', None) or {}
    if name in aliases:
        return aliases[name]
    return aliases.get(name.lower(), name)


def _simple_parse(line, data_module=None):
    """adventure.py 不可用时的备用解析器 / Fallback parser used if adventure.py fails."""
    tokens = line.split()
    if not tokens:
        raise SyntaxError(T('没有输入命令', 'No command given'))
    command = tokens.pop(0)
    if command in ('talk', 'go'):
        if not tokens or tokens[0] != 'to':
            raise SyntaxError(T('你是想说 "{} to [名字]" 吗？'.format(command),
                                'Did you mean "{} to [name]"?'.format(command)))
        operator, operand = command + '_to', ' '.join(tokens[1:])
    elif command == 'check':
        if not tokens or tokens[0] != 'backpack':
            raise SyntaxError(T('你是想说 "check backpack" 吗？',
                                'Did you mean "check backpack"?'))
        operator, operand = 'check_backpack', ''
    elif command == 'unlock':
        operator, operand = 'unlock', ' '.join(tokens)
    else:
        operator, operand = command, ' '.join(tokens)
    if operator in ('go_to', 'talk_to', 'take', 'unlock'):
        operand = _localize(operand, data_module)
    return (operator, operand)


# =============================================================================
# GameSession：把学生写的游戏逻辑包起来，给界面调用
# GameSession: wraps the student's game logic so the interface can call it
# =============================================================================

class GameSession(object):
    """负责载入代码、调用玩家方法、捕获输出、判断状态的工作。"""

    def __init__(self):
        self.classes = None
        self.data = None
        self.me = None
        self.adventure = None
        self.load_error = None
        self.places = []
        self.load(do_reload=False)

    # ---------------------------------------------------------------- 载入
    def load(self, do_reload=False):
        """导入（或重新导入）classes.py 与 data.py，成功返回 True。"""
        if PROJECT_DIR not in sys.path:
            sys.path.insert(0, PROJECT_DIR)
        self.load_error = None
        self.classes = self.data = self.me = None
        self.places = []
        try:
            classes_module = importlib.import_module('classes')
            if do_reload:
                classes_module = importlib.reload(classes_module)
            data_module = importlib.import_module('data')
            if do_reload:
                data_module = importlib.reload(data_module)
            if do_reload and 'adventure' in sys.modules:
                importlib.reload(sys.modules['adventure'])
        except Exception:
            self.load_error = traceback.format_exc()
            return False
        self.classes = classes_module
        self.data = data_module
        self.me = getattr(data_module, 'me', None)
        self.adventure = sys.modules.get('adventure')
        self.places = [value for value in vars(data_module).values()
                       if isinstance(value, classes_module.Place)]
        return True

    # ---------------------------------------------------------------- 查询
    def has_player(self):
        """data.py 里是否已经创建了 Player 对象。"""
        if self.classes is None or self.me is None:
            return False
        try:
            return isinstance(self.me, self.classes.Player)
        except AttributeError:
            return False

    def place(self):
        """玩家当前所在的 Place（没有就返回 None）。"""
        return getattr(self.me, 'place', None) if self.me is not None else None

    def view(self):
        """把当前状态整理成界面直接可以画出来的字典。"""
        place = self.place()
        if place is None:
            return None
        info = {
            'name': getattr(place, 'name', '?'),
            'description': getattr(place, 'description', ''),
            'locked': bool(getattr(place, 'locked', False)),
            'exits': [],
            'things': [],
            'characters': [],
            'backpack': [],
        }
        for exit_name, exit_value in getattr(place, 'exits', {}).items():
            description = ''
            if isinstance(exit_value, (tuple, list)) and exit_value:
                target = exit_value[0]
                if len(exit_value) > 1 and exit_value[1]:
                    description = exit_value[1]
            else:
                target = exit_value
            info['exits'].append({
                'name': getattr(target, 'name', exit_name) or exit_name,
                'description': description,
                'locked': bool(getattr(target, 'locked', False)),
            })
        for thing in getattr(place, 'things', {}).values():
            info['things'].append({
                'name': getattr(thing, 'name', '?'),
                'description': getattr(thing, 'description', ''),
            })
        for name, character in getattr(place, 'characters', {}).items():
            info['characters'].append({'name': getattr(character, 'name', name)})
        for item in (getattr(self.me, 'backpack', None) or []):
            info['backpack'].append({
                'name': getattr(item, 'name', str(item)),
                'description': getattr(item, 'description', ''),
            })
        return info

    def signature(self):
        """游戏状态的“指纹”，用来判断一次操作有没有真的改变状态。"""
        place = self.place()
        backpack = tuple(sorted(getattr(item, 'name', str(item))
                                for item in (getattr(self.me, 'backpack', None) or [])))
        locks = tuple(sorted((getattr(place_object, 'name', str(place_object)),
                              bool(getattr(place_object, 'locked', False)))
                             for place_object in self.places))
        return (id(place), backpack, locks)

    def is_win(self):
        """是否达成了胜利条件（在大礼堂 + 背包里有 Smoothie 和 Lemon）。"""
        try:
            place = self.place()
            if place is None:
                return False
            if place is not getattr(self.data, 'hp', None) \
                    and getattr(place, 'name', '') not in WIN_PLACE_NAMES:
                return False
            names = {getattr(item, 'name', str(item))
                     for item in (getattr(self.me, 'backpack', None) or [])}
            return set(WIN_ITEM_NAMES).issubset(names)
        except Exception:
            return False

    # ---------------------------------------------------------------- 调用
    def _capture(self, function, *args):
        """执行学生代码，并把它 print 出来的文字收集起来。"""
        buffer = io.StringIO()
        real_stdout, real_input = sys.stdout, builtins.input

        def blocked_input(prompt=''):
            raise EOFError(T(
                '图形界面里不能使用 input()，请使用界面按钮或下方的命令输入框。',
                'input() is not available in the GUI - use the buttons or the command box.'))

        sys.stdout = buffer
        builtins.input = blocked_input
        error = None
        try:
            function(*args)
        except Exception:
            error = traceback.format_exc()
        finally:
            sys.stdout = real_stdout
            builtins.input = real_input
        return buffer.getvalue(), error

    def call(self, method_name, *args):
        """调用学生自己实现的 Player 方法，返回 (输出文本, 错误信息或 None)。"""
        if self.me is None:
            return (T('data.py 的最后一行还没有创建 Player 对象，所以还没法玩。',
                      'There is no Player object at the bottom of data.py yet, so the game '
                      'cannot start.'), None)
        method = getattr(self.me, method_name, None)
        if method is None:
            return (T('Player 类里没有 {} 方法。'.format(method_name),
                      'The Player class has no {} method.'.format(method_name)), None)
        return self._capture(method, *args)

    def parse(self, line):
        """解析一行命令；优先用 adventure.py 的解析器，保证与文字版完全一致。"""
        if self.adventure is None and self.data is not None:
            try:
                importlib.import_module('adventure')
            except Exception:
                self.adventure = None
            else:
                self.adventure = sys.modules.get('adventure')
        parser = getattr(self.adventure, 'adv_parse', None)
        if parser is not None:
            return parser(line)
        return _simple_parse(line, self.data)

    def command_formats(self):
        """命令列表（来自 adventure.py，取不到就用备用列表）。"""
        formats = getattr(self.adventure, 'COMMAND_FORMATS', None)
        if formats:
            return list(formats.values())
        return [
            'look                     # 看看周围',
            'go to [place]             # 去往某个地点',
            'take [thing]              # 拿走某个物品',
            'talk to [character]       # 和某个角色交谈',
            'check backpack            # 查看背包',
            'help                      # 显示命令列表',
            'unlock [place]            # 用钥匙解锁某个地点',
        ]

    # ---------------------------------------------------------------- 提示
    def remaining_stubs(self):
        """找出 classes.py / data.py 里还没删掉的 "*** YOUR CODE HERE ***"。"""
        stubs = []
        for module in (self.classes, self.data):
            path = getattr(module, '__file__', None)
            if not path:
                continue
            for number, line in enumerate(_read_lines(path), 1):
                if '*** YOUR CODE HERE ***' in line or 'Implement Key here' in line:
                    stubs.append((path, number, line.strip()))
        return stubs

    def stub_line(self, method_name):
        """返回 classes.py 里某个方法内 YOUR CODE HERE 的行号（找不到就返回 None）。"""
        if self.classes is None:
            return None
        path = getattr(self.classes, '__file__', None)
        if not path:
            return None
        lines = _read_lines(path)
        start = None
        for index, line in enumerate(lines):
            if line.lstrip().startswith('def {}('.format(method_name)):
                start = index
                break
        if start is None:
            return None
        indent = len(lines[start]) - len(lines[start].lstrip())
        for index in range(start + 1, len(lines)):
            stripped = lines[index].strip()
            current_indent = len(lines[index]) - len(lines[index].lstrip())
            if stripped.startswith('def ') and current_indent <= indent:
                break
            if '*** YOUR CODE HERE ***' in stripped:
                return index + 1
        return None

    def location_of(self, method_name):
        """给出方法的位置描述，例如 'classes.py:31'。"""
        line = self.stub_line(method_name)
        if line is None:
            return 'classes.py'
        return 'classes.py:{}'.format(line)

    def no_change_hint(self, method_name):
        """操作之后状态没有变化时，给出的双语提示。"""
        where = self.location_of(method_name)
        if method_name == 'go_to':
            return T(
                '咦，玩家好像没有移动：Player.go_to 可能还没写完（{}）。另外，如果目的地旁边有 🔒，'
                '说明它上锁了，需要先找到钥匙再用 unlock。'.format(where),
                'Hmm, the player did not move: Player.go_to looks unfinished ({}). '
                'Also, if the destination shows a 🔒 it is locked - find the key and unlock it '
                'first.'.format(where))
        if method_name == 'take':
            return T(
                '背包没有变化：Player.take 可能还没写完（{}），或者这件物品根本不在你所在的地点。'.format(where),
                'The backpack did not change: Player.take looks unfinished ({}), or the thing is '
                'simply not where you are.'.format(where))
        if method_name == 'unlock':
            return T(
                '这门还是锁着：Player.unlock 可能还没写完（{}），或者你的背包里还没有钥匙。'.format(where),
                'The place is still locked: Player.unlock looks unfinished ({}), or there is no key '
                'in your backpack yet.'.format(where))
        if method_name == 'talk_to':
            return T(
                '聊天好像没有任何输出：Player.talk_to 可能还没写完（{}）。'.format(where),
                'Talking produced no output: Player.talk_to looks unfinished ({}).'.format(where))
        return T('这次操作好像没有改变任何状态（{}）。'.format(where),
                 'That action did not change anything ({}).'.format(where))

    def error_hint(self, method_name):
        """学生代码抛异常时的双语说明。"""
        if method_name == 'unlock':
            return T(
                '提示：unlock 里会用到 Key 类，如果你还没有实现 Key，就会看到 NameError。'
                '请先在 classes.py 里写完 Key（它是 Thing 的子类）。',
                'Hint: unlock uses the Key class. Until you implement Key you will see a NameError - '
                'write the Key class in classes.py first (it is a subclass of Thing).')
        return T(
            '上面是 Python 报的错。看看 {} 里的代码，再对照它的 docstring（doctest）检查一下。'.format(
                self.location_of(method_name)),
            'That is the Python error. Re-read {} and compare with its docstring (the doctests).'.format(
                self.location_of(method_name)))

    def hint_lines(self):
        """“提示”按钮显示的内容（中英双语）。"""
        lines = [
            T('目标：带上一杯奶昔（Smoothie）和一个柠檬（Lemon），去大礼堂参加学习聚会。',
              'Goal: bring a Smoothie and a Lemon to the Auditorium (大礼堂).'),
            T('玩法：点击按钮，或者在下面输入命令（支持英文别名，例如 `go to GBC`）。',
              'How to play: click the buttons, or type commands below (English aliases such as '
              '`go to GBC` work too).'),
        ]
        if not self.has_player():
            line = None
            for path, number, text in self.remaining_stubs():
                if os.path.basename(path) == 'data.py':
                    line = number
            where = 'data.py:{}'.format(line) if line else 'data.py'
            lines.append(T('第一件事：在 {} 的最后创建 Player 对象，例如 me = Player("你的名字", sather_gate)。'.format(where),
                           'First step: create the player at the bottom of {} (see Q1), e.g. '
                           'me = Player("your name", sather_gate).'.format(where)))
            return lines

        stubs = self.remaining_stubs()
        if stubs:
            lines.append(T('还没删掉的 *YOUR CODE HERE* 标记：',
                           'Leftover *YOUR CODE HERE* markers:'))
            for path, number, _text in stubs:
                lines.append('    {}:{}'.format(os.path.basename(path), number))
        else:
            lines.append(T('不错：*YOUR CODE HERE* 标记都已经删掉了。',
                           'Nice: all *YOUR CODE HERE* markers are gone.'))

        for method_name, zh, en in METHOD_HINTS:
            lines.append('    [{}] {}'.format(self.location_of(method_name), T(zh, en)))
        lines.append(T('更多说明见 README.md / Questions.md（中英双语）。',
                       'More details are in README.md / Questions.md (bilingual).'))
        return lines


