    # ------------------------------------------------------------ 日志
    def log(self, text, tag=None):
        if not text:
            return
        if not text.endswith('\n'):
            text += '\n'
        self.log_view.configure(state='normal')
        self.log_view.insert('end', text, tag)
        self.log_view.configure(state='disabled')
        self.log_view.see('end')

    def _snapshot_log(self):
        """把日志内容按 (标签, 文本) 存下来，切换语言时用来还原。"""
        entries = []
        current_tag = None
        for kind, value, _index in self.log_view.dump('1.0', 'end-1c', text=True, tag=True):
            if kind == 'text':
                entries.append((current_tag, value))
            elif kind == 'tagon':
                current_tag = value
            elif kind == 'tagoff':
                current_tag = None
        return entries

    def _report_callback_exception(self, exc_type, exc_value, exc_tb):
        self.log(''.join(traceback.format_exception(exc_type, exc_value, exc_tb)), 'error')

