    # ------------------------------------------------------------ 刷新界面
    def refresh(self):
        for frame in (self.exits_frame, self.things_frame,
                      self.characters_frame, self.backpack_frame):
            for child in frame.winfo_children():
                child.destroy()

        if self.session.load_error:
            self.place_label.configure(text=T('载入失败', 'Loading failed'))
            self.place_desc.configure(text=T('请先修好 data.py / classes.py 里的错误。',
                                             'Fix the errors in data.py / classes.py first.'))
            note = T('载入失败，先看看下面的错误信息。',
                     'Loading failed - see the error below.')
            self._render_note(self.exits_frame, note)
            self._render_note(self.things_frame, note)
            self._render_note(self.characters_frame, note)
            self._render_note(self.backpack_frame, note)
            self._show_load_error()
            return

        if not self.session.has_player():
            self.place_label.configure(text=T('还没有玩家', 'No player yet'))
            self.place_desc.configure(text=T(
                '在 data.py 的最后创建 Player 对象（Q1），然后点“重新加载代码”。',
                'Create the Player object at the bottom of data.py (Q1), then click "Reload code".'))
            self._render_note(self.exits_frame, T('完成 Q1 之后，这里会显示可以去的地方。',
                                                  'Finish Q1 and the places you can walk to show '
                                                  'up here.'))
            self._render_note(self.things_frame, '—')
            self._render_note(self.characters_frame, '—')
            self._render_note(self.backpack_frame, T('背包还是空的。', 'Your backpack is empty.'))
            self._warn_missing_player()
            return

        view = self.session.view()
        if view is None:
            self.place_label.configure(text=T('拿不到玩家位置', 'No player place'))
            self.place_desc.configure(text=T(
                'me.place 好像被改坏了：检查 data.py 中创建玩家时传入的地点。',
                'me.place looks broken: check the place you passed to Player(...) in data.py.'))
            return

        lock_mark = ' 🔒' if view['locked'] else ''
        self.place_label.configure(text=view['name'] + lock_mark)
        self.place_desc.configure(text=view['description'])
        self._render_exits(view['exits'])
        self._render_things(view['things'])
        self._render_characters(view['characters'])
        self._render_backpack(view['backpack'])
        self._autosize()

    def _autosize(self):
        """把窗口调整到刚好放得下内容（不超过屏幕，且只增不减）。

        Resize the window to fit its content, capped by the screen size; the window
        only ever grows, so the panels are never squeezed.  The log keeps its
        scrollbar, so it can absorb a shortfall on small screens.
        """
        self.root.update_idletasks()
        need_width = min(max(self.root.winfo_reqwidth(), 880), 1120)
        need_height = min(self.root.winfo_reqheight(),
                          max(self.root.winfo_screenheight() - 110, 560))
        need_height = max(need_height, 560)
        current_width = max(self.root.winfo_width(), 1)
        current_height = max(self.root.winfo_height(), 1)
        if need_width > current_width or need_height > current_height:
            self.root.geometry('{}x{}'.format(max(need_width, current_width),
                                              max(need_height, current_height)))

